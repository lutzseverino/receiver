// PROTOTYPE helper: writes glyph-table.js, the approved glyph table, from the round-1 bitmaps in glyphs.js
// and the owner's verdicts (lutzseverino/site#8, 2026-11-02). run: node prototype/make-glyph-table.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const window = {}; new Function('window', readFileSync(dir + 'glyphs.js', 'utf8'))(window);
const { A, B, toBytes } = window.GLYPHS;

// the verdicts: which round-1 variant each glyph comes from ('=' marks a glyph that is the same in A and B)
const FROM = {
  'á': 'A', 'à': 'A', 'é': 'A', 'è': 'A', 'í': 'A', 'ó': 'A', 'ò': 'A', 'ú': 'A',
  'Á': 'A', 'À': 'A', 'É': 'A', 'È': 'A', 'Í': 'A', 'Ó': 'A', 'Ò': 'A', 'Ú': 'A',
  'ï': '=', 'ü': '=', 'Ï': '=', 'Ü': '=', 'ñ': '=', '¿': '=', '¡': '=', 'º': '=', 'ª': '=',
  'ç': 'B', 'Ç': 'B', '«': 'A', '»': 'A',
};
// Ñ, drawn in round 2: the owner's exception to D17, a 5-row N (rows 2–6) under ñ's two-row wave (rows 0–1)
const NEW = { 'Ñ': [...A.rows['ñ'].slice(0, 2), 'X...X', 'XX..X', 'X.X.X', 'X..XX', 'X...X'] };

const hex = a => '[' + a.map(x => '0x' + x.toString(16).toUpperCase().padStart(2, '0')).join(', ') + ']';
const G = {}, G8 = {}, ROWS = {}, SRC = {};
for (const [ch, v] of Object.entries(FROM)) {
  if (v === '=' && (hex(A.g7[ch]) !== hex(B.g7[ch]) || hex(A.g8[ch] || []) !== hex(B.g8[ch] || []))) throw new Error(`${ch} differs between A and B`);
  const s = v === 'B' ? B : A; G[ch] = s.g7[ch]; if (s.g8[ch]) G8[ch] = s.g8[ch]; ROWS[ch] = s.rows[ch]; SRC[ch] = v === '=' ? 'A = B' : v;
}
for (const [ch, r] of Object.entries(NEW)) { G[ch] = toBytes(r); ROWS[ch] = r; SRC[ch] = 'round 2'; }
// ç's 7-row form (big text, 5×7 places) is B's raised c, which glyphs.js derives; record its rows too
const rowsOf = (bytes, n) => Array.from({ length: n }, (_, r) => [0, 1, 2, 3, 4].map(c => (bytes[c] >> r) & 1 ? 'X' : '.').join(''));

const order = 'áàéèíïóòúüñçÁÀÉÈÍÏÓÒÚÜÑÇ¿¡«»ºª';
if ([...order].sort().join('') !== Object.keys(G).sort().join('')) throw new Error('table and order disagree');
const line = (ch, bytes, n) => `    '${ch}': ${hex(bytes)},`.padEnd(48) + `// ${rowsOf(bytes, n).join(' ')}  (${SRC[ch]})`;
const out = `/* Glyph table for the receiver's dot font: accented letters and marks for Spanish and Catalan.
   APPROVED by the owner, 2026-11-02 (lutzseverino/site#8, verdicts at
   https://github.com/lutzseverino/site/issues/8#issuecomment-6573270693); built in by #9 (Draft 5).
   Generated by make-glyph-table.mjs from glyphs.js; do not edit by hand.

   Shape, as round 13's font: G holds five column bytes per glyph, bit 0 at the top, rows 0–6 (5×7).
   G8 holds the 8-row form (bit 7 = the descender row of the 5×8 cell) for a glyph that uses row 7;
   5×8 text cells take G8 first, and 7-row places (big text, the 5×7 display) take G.
   Comments draw each glyph's rows top to bottom ('X' lit) and say where it comes from: round-1
   variant A or B, "A = B" where both were the same, or "round 2" for Ñ.

   Rules: lowercase keeps the 5×7 body with the accent in rows 0–1. Accented capitals are 6 rows with the
   accent on top (D17), except Ñ: a 5-row N under ñ's two-row wave (the owner's exception to D17).
   Ç is a 6-row C raised one row, with the cedilla in row 6, in text and big text alike.
   The middle dot (l·l) is round 13's '·' unchanged (row 3); it is not in this table. */
window.GLYPH_TABLE = {
  G: {
${[...order].map(ch => line(ch, G[ch], 7)).join('\n')}
  },
  G8: {
${Object.keys(G8).map(ch => line(ch, G8[ch], 8)).join('\n')}
  },
};
`;
writeFileSync(dir + 'glyph-table.js', out);
console.log(out);
