/** The signal-strength glyph for `n` of five rising bars. */
export function signal(n: number): string {
  return String.fromCharCode(0xe000 + Math.max(0, Math.min(5, Math.round(n))));
}
for (let n = 0; n <= 5; n++)
  G[signal(n)] = [0, 1, 2, 3, 4].map((i) => {
    const h = 2 + i;
    return i < n ? ((1 << h) - 1) << (7 - h) : 0;
  });

/** Typographic punctuation and the ASCII forms the font draws instead. */
const PUNCTUATION: Record<string, string> = {
  "—": "-",
  "–": "-",
  "“": '"',
  "”": '"',
  "‘": "'",
  "’": "'",
  "…": "...",
};

/** `text` as the display draws it: typographic punctuation in its ASCII
 * forms, and every run of whitespace, such as a line break or a no-break
 * space, as one space. */
export function displayText(text: string): string {
  return text
    .replace(/[—–“”‘’…]/g, (mark) => PUNCTUATION[mark]!)
    .replace(/\s+/g, " ");
}

const own = (ch: string): Glyph | undefined =>
  Object.hasOwn(G, ch) ? G[ch] : undefined;

/** The 7-row glyph for `ch`, its capital's when the font has only that, or
 * `?` for a character the font lacks, which the build never lets through. */
export function glyph(ch: string): Glyph {
  return own(ch) ?? own(ch.toUpperCase()) ?? G["?"]!;
}

/** The glyph a 5×8 text cell draws: its 8-row form, if it has one. */
export function glyph8(ch: string): Glyph {
  return (Object.hasOwn(G8, ch) ? G8[ch] : undefined) ?? glyph(ch);
}

/** Each distinct character of `text`, after the punctuation mapping, that
 * the font lacks, in order of first appearance. */
export function uncovered(text: string): string[] {
  const missing = new Set<string>();
  for (const ch of displayText(text))
    if (!own(ch) && !own(ch.toUpperCase())) missing.add(ch);
  return [...missing];
}
